  CONSTRAINT fk_timetable_versions_created_by FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_timetable_versions_reviewed_by FOREIGN KEY (reviewed_by) REFERENCES users(id),
  CONSTRAINT fk_timetable_versions_approved_by FOREIGN KEY (approved_by) REFERENCES users(id),
  CONSTRAINT fk_timetable_versions_published_by FOREIGN KEY (published_by) REFERENCES users(id)
