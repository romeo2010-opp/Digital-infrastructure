USE smartlink_schools;

CREATE TABLE IF NOT EXISTS timetable_rooms (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  school_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(60) NOT NULL,
  name VARCHAR(160) NOT NULL,
  room_type ENUM('ordinary_classroom', 'laboratory', 'computer_lab', 'library', 'workshop', 'art_room', 'music_room', 'sports_ground', 'hall', 'special_needs', 'office', 'custom') NOT NULL DEFAULT 'ordinary_classroom',
  capacity INT UNSIGNED NULL,
  exam_capacity INT UNSIGNED NULL,
  building VARCHAR(120) NULL,
  floor_label VARCHAR(60) NULL,
  accessibility JSON NULL,
  equipment JSON NULL,
  home_class_id BIGINT UNSIGNED NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_timetable_rooms_school_code (school_id, code),
  KEY idx_timetable_rooms_school_type (school_id, room_type, active),
  CONSTRAINT fk_timetable_rooms_school FOREIGN KEY (school_id) REFERENCES schools(id),
  CONSTRAINT fk_timetable_rooms_home_class FOREIGN KEY (home_class_id) REFERENCES classes(id),
  CONSTRAINT fk_timetable_rooms_created_by FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS timetable_resources (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  school_id BIGINT UNSIGNED NOT NULL,
