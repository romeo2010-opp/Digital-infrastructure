CREATE TABLE IF NOT EXISTS timetables (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  school_id BIGINT UNSIGNED NOT NULL,
  timetable_type ENUM('SCHOOL_TIMETABLE', 'EXAM_TIMETABLE') NOT NULL,
  name VARCHAR(180) NOT NULL,
  academic_year_id BIGINT UNSIGNED NOT NULL,
  term_id BIGINT UNSIGNED NULL,
  cycle_type ENUM('NORMAL_WEEK', 'WEEK_A_WEEK_B', 'ROTATING_CYCLE', 'DATED_EXAM_SESSIONS', 'CUSTOM') NOT NULL DEFAULT 'NORMAL_WEEK',
  effective_from DATE NOT NULL,
  effective_to DATE NOT NULL,
  status ENUM('SETUP', 'VALIDATION_REQUIRED', 'READY', 'GENERATING', 'DRAFT', 'UNDER_REVIEW', 'CHANGES_REQUESTED', 'APPROVED', 'PUBLISHED', 'SUPERSEDED', 'ARCHIVED') NOT NULL DEFAULT 'SETUP',
  current_published_version_id BIGINT UNSIGNED NULL,
  setup_progress JSON NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_timetables_school_context_name (school_id, timetable_type, academic_year_id, term_id, name),
  KEY idx_timetables_school_type_status (school_id, timetable_type, status),
  KEY idx_timetables_context (school_id, academic_year_id, term_id),
  CONSTRAINT fk_timetables_school FOREIGN KEY (school_id) REFERENCES schools(id),
  CONSTRAINT fk_timetables_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
  CONSTRAINT fk_timetables_term FOREIGN KEY (term_id) REFERENCES terms(id),
  CONSTRAINT fk_timetables_created_by FOREIGN KEY (created_by) REFERENCES users(id)
);

