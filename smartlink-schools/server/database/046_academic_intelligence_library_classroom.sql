-- Preserve existing drill mastery as low-confidence topic evidence without
-- pretending it contains objective-level detail.
INSERT INTO academic_mastery_records (
  public_ref, school_id, student_id, subject_id, topic_id, mastery_level,
  mastery_score, confidence_score, mastery_status, trend, evidence_count,
  calculation_explanation_json, last_evidence_at, last_recalculated_at
)
SELECT UUID(), stm.school_id, stm.student_id, stm.subject_id, stm.topic_id, 'topic',
  stm.mastery_score,
  CASE stm.confidence_label WHEN 'high' THEN 80 WHEN 'medium' THEN 55 ELSE 30 END,
  CASE
    WHEN stm.attempts = 0 THEN 'NOT_ASSESSED'
    WHEN stm.attempts < 3 THEN 'INSUFFICIENT_EVIDENCE'
    WHEN stm.intervention_needed = 1 THEN 'REQUIRES_INTERVENTION'
    WHEN stm.mastery_score >= 85 THEN 'ADVANCED'
    WHEN stm.mastery_score >= 70 THEN 'MASTERED'
    WHEN stm.mastery_score >= 50 THEN 'PARTIALLY_MASTERED'
    WHEN stm.mastery_score >= 35 THEN 'DEVELOPING'
    ELSE 'EMERGING'
  END,
  UPPER(stm.trend), stm.attempts,
  JSON_OBJECT('source','student_topic_mastery','migration','046','granularity','topic'),
  stm.last_practised_at, CURRENT_TIMESTAMP
FROM student_topic_mastery stm
ON DUPLICATE KEY UPDATE
  mastery_score = VALUES(mastery_score),
  confidence_score = VALUES(confidence_score),
  evidence_count = VALUES(evidence_count),
  last_evidence_at = VALUES(last_evidence_at),
  last_recalculated_at = CURRENT_TIMESTAMP;

