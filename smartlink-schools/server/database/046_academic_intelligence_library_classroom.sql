UPDATE learning_objectives lo
JOIN syllabus_topics st ON st.id = lo.topic_id
SET lo.school_id = st.school_id,
    lo.subject_id = st.subject_id,
    lo.public_ref = COALESCE(lo.public_ref, UUID())
WHERE lo.school_id IS NULL OR lo.subject_id IS NULL OR lo.public_ref IS NULL;

