test("teachers cannot approve, publish, or edit another teacher's parent update", () => {
  const start = source.indexOf("export async function updateParentAcademicInsight")
  const end = source.indexOf("export async function getParentPortalAcademicInsights", start)
  const update = source.slice(start, end)
  assert.match(update, /Number\(before\.created_by\)!==Number\(actor\.id\)/)
  assert.match(update, /before\.status!=='draft'\|\|status!=='draft'/)
  assert.match(update, /approved and published by academic leadership/)
  assert.match(update, /assignment\.role='subject_teacher'/)
  assert.match(update, /assignment\.academic_year_id=\?/)
  assert.match(update, /assignment\.term_id=\?/)
  assert.doesNotMatch(update, /assignment\.academic_year_id IS NULL/)
  assert.doesNotMatch(update, /assignment\.term_id IS NULL/)
  assert.match(update, /ORDER BY current_term\.id IS NULL/)
})
